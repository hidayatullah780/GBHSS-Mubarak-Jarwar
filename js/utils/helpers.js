/** Professional empty state — used wherever no real records exist yet. */
export function emptyState(iconName, title, text) {
  return `<div class="empty-state">${icon(iconName, 40)}<h3>${escapeHtml(title)}</h3><p>${escapeHtml(text)}</p></div>`;
}
